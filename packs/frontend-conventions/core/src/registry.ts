const byId = new Map<string, RuleMetadata>();
for (const meta of ruleRegistry) byId.set(meta.id, meta);

export function getRuleMetadata(ruleId: string): RuleMetadata | undefined {
    return byId.get(ruleId);
}

/** Все активные правила (REDUX-8 — нет). */
export function allActiveRules(): RuleMetadata[] {
    return ruleRegistry.filter((r) => r.active);
}

/** Правила, доступные как ESLint-правила (полностью или чисто-AST частью). */
export function eslintSupportedRules(): RuleMetadata[] {
    return ruleRegistry.filter((r) => r.active && r.eslint.supported);
}

export function getRuleSource(ruleId: string): "wiki" | "mr-pattern" {
    return getRuleMetadata(ruleId)?.source ?? "mr-pattern";
}

export function getRuleTitle(ruleId: string): string {
    return getRuleMetadata(ruleId)?.title ?? ruleId;
}

export function getRuleSeverity(ruleId: string): import("./types.js").Severity {
    return getRuleMetadata(ruleId)?.severity ?? "SHOULD";
}
